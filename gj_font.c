void gj_font_glyph(char ch, uint8_t rows[5]) {
    unsigned u = (unsigned char)ch;
    if(u < 32 || u > 126) {
        rows[0] = rows[4] = 0;
        rows[1] = rows[2] = rows[3] = 0x07; /* 3px box */
        return;
    }
    memcpy(rows, GJ_FONT_ROWS[u - 32], 5);
}
