void gj_font_glyph(char ch, uint8_t rows[7]) {
    const char* s = 0;
    unsigned u = (unsigned char)ch;
    if(u >= 32 && u <= 126) s = G[u - 32];
    for(int r = 0; r < 7; r++) rows[r] = 0;
    if(!s) {
        rows[2] = rows[3] = rows[4] = 0x07; /* 3px box cols 0..2 */
        return;
    }
    /* Tolerant scan: ignore spaces, 5 cells per row, stop at NUL. */
    int r = 0, c = 0;
    for(const char* p = s; *p && r < 7; p++) {
        if(*p == ' ') continue;
        if(*p == '#') rows[r] = (uint8_t)(rows[r] | (1u << c));
        if(++c == 5) {
            c = 0;
            r++;
        }
    }
}
